namespace LABA_3.Drawing
{
    /// <summary>
    /// Способы растеризации треугольника. Оба заливают одно и то же множество
    /// пикселей (треугольник = пересечение трёх полуплоскостей), но обходят
    /// канву по-разному: построчно либо перебором ограничивающего прямоугольника.
    /// </summary>
    public enum TriangleRasterizer
    {
        /// <summary>
        /// Построчное сканирование: для каждой строки находится отрезок пересечения
        /// с границами треугольника, цвет считается барицентрическими весами,
        /// которые накапливаются приращениями при движении по строке.
        /// </summary>
        ScanLineBarycentric,

        /// <summary>
        /// Перебор ограничивающего прямоугольника с проверкой трёх
        /// функций-полуплоскостей (edge functions).
        /// </summary>
        EdgeFunctions
    }
}
